export function icone(nome, classe = "") {
    const caminho = ICONES[nome];
    if (!caminho) return "";
    return `<svg class="ico ${classe}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${caminho}</svg>`;
}

export function hidratarIcones(raiz = document) {
    raiz.querySelectorAll("i[data-icon]").forEach(el => {
        el.outerHTML = icone(el.dataset.icon);
    });
}
